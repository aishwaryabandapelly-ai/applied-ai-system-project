"""
Baseline vs specialized comparison for TuneGuide AI (specialization stretch).

For each natural-language request, compares:
- Baseline: the pipeline WITHOUT the interpreter (no structured profile to work
  from), which cannot build a profile and fails validation.
- Specialized: the pipeline WITH the deterministic preference interpreter, which
  infers a structured profile and completes the request.

Both paths use the integrated ``RecommendationAgent``; no recommendation or
evaluator logic is duplicated. Also writes ``experiments/specialization_results.md``.

Reproducible and non-interactive:

    python -m experiments.run_specialization_comparison
"""

from src.recommender import load_songs
from src.agent import RecommendationAgent

RESULTS_PATH = "experiments/specialization_results.md"

REQUESTS = [
    "I'm studying for my robotics exam.",
    "I'm lifting weights.",
    "I'm driving home after work.",
    "I'm coding late at night.",
    "I need relaxing music while reading.",
    "Help me fall asleep.",
    "I want something nostalgic.",
    "I'm feeling energetic.",
]


def summarize(result) -> dict:
    summary = {
        "success": result.success,
        "profile": dict(result.cleaned_profile) if result.cleaned_profile else {},
        "candidates": result.metadata.get("retrieved_candidates", 0),
        "recommendations": result.metadata.get("returned_recommendations", 0),
        "confidence": result.metadata.get("interpretation_confidence"),
        "reliability": None,
    }
    if result.success and result.reliability_report is not None:
        summary["reliability"] = result.reliability_report.score
    return summary


def improved(baseline: dict, specialized: dict) -> str:
    if not baseline["success"] and specialized["success"]:
        return "Yes — specialization enabled a request the baseline could not interpret."
    if specialized["candidates"] > baseline["candidates"]:
        return "Yes — more relevant candidates retrieved."
    return "No measurable change."


def run_case(agent, request):
    baseline = summarize(agent.recommend({}, k=5))  # no interpreter, no profile
    specialized = summarize(agent.recommend({}, k=5, natural_language_request=request))
    return {
        "request": request,
        "baseline": baseline,
        "specialized": specialized,
        "improved": improved(baseline, specialized),
    }


def _fmt(value) -> str:
    return "—" if value is None else str(value)


def print_case(case) -> None:
    b, s = case["baseline"], case["specialized"]
    print("=" * 72)
    print(f"Request       : {case['request']}")
    print(f"  Baseline    : success={b['success']} candidates={b['candidates']} "
          f"recs={b['recommendations']} reliability={_fmt(b['reliability'])} profile={b['profile'] or '{}'}")
    print(f"  Specialized : success={s['success']} candidates={s['candidates']} "
          f"recs={s['recommendations']} reliability={_fmt(s['reliability'])} confidence={_fmt(s['confidence'])}")
    print(f"  Profile     : {s['profile']}")
    print(f"  Improved    : {case['improved']}")


def write_markdown(cases) -> None:
    lines = []
    lines.append("# TuneGuide AI — Specialization Before/After Comparison")
    lines.append("")
    lines.append(
        "Verified results comparing the baseline pipeline (no interpreter) with "
        "the specialized pipeline (deterministic natural-language preference "
        "interpreter). Both use the integrated `RecommendationAgent`. The baseline "
        "receives only a natural-language request with no structured profile, so "
        "it cannot build a profile and fails validation."
    )
    lines.append("")
    lines.append("*Generated by `python -m experiments.run_specialization_comparison`.*")
    lines.append("")
    lines.append("## Summary")
    lines.append("")
    lines.append("| Request | Baseline | Specialized profile | Confidence | Candidates (base → spec) | Reliability | Improved retrieval |")
    lines.append("|---------|----------|---------------------|------------|--------------------------|-------------|--------------------|")
    for c in cases:
        b, s = c["baseline"], c["specialized"]
        base_state = "success" if b["success"] else "validation failed"
        prof = ", ".join(f"{k}={v}" for k, v in s["profile"].items()) if s["profile"] else "—"
        cand = f"{b['candidates']} → {s['candidates']}"
        yn = "Yes" if c["improved"].startswith("Yes") else "No"
        lines.append(
            f"| {c['request']} | {base_state} | {prof} | {_fmt(s['confidence'])} | {cand} | "
            f"{_fmt(s['reliability'])} | {yn} |"
        )
    lines.append("")
    lines.append("## Case Details")
    lines.append("")
    for c in cases:
        b, s = c["baseline"], c["specialized"]
        lines.append(f"### {c['request']}")
        lines.append("")
        lines.append("| Field | Baseline | Specialized |")
        lines.append("|-------|----------|-------------|")
        lines.append(f"| success | {b['success']} | {s['success']} |")
        lines.append(f"| inferred confidence | — | {_fmt(s['confidence'])} |")
        lines.append(f"| profile | {b['profile'] or '{}'} | {s['profile']} |")
        lines.append(f"| retrieved candidates | {b['candidates']} | {s['candidates']} |")
        lines.append(f"| recommendations | {b['recommendations']} | {s['recommendations']} |")
        lines.append(f"| reliability score | {_fmt(b['reliability'])} | {_fmt(s['reliability'])} |")
        lines.append("")
        lines.append(f"**Improved retrieval:** {c['improved']}")
        lines.append("")

    with open(RESULTS_PATH, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def main() -> None:
    songs = load_songs("data/songs.csv")
    agent = RecommendationAgent(songs)

    cases = [run_case(agent, request) for request in REQUESTS]
    for case in cases:
        print_case(case)
    print("=" * 72)

    write_markdown(cases)
    print(f"Comparison table written to {RESULTS_PATH}")


if __name__ == "__main__":
    main()
